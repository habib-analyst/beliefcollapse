"""Contamination report rendering (text + HTML)."""
from __future__ import annotations

import html


def _bar(rate: float | None, width: int = 24) -> str:
    if rate is None:
        return "(n/a)"
    filled = int(round(rate * width))
    return "[" + "#" * filled + "-" * (width - filled) + f"] {rate:.1%}"


def render_text(agg: dict, title: str = "beliefcollapse report") -> str:
    lines = [title, "=" * len(title), ""]
    lines.append(f"discussions: {agg['n_discussions']}")
    for cond, m in agg["by_condition"].items():
        lines.append("")
        lines.append(f"condition {cond} "
                     f"({m['n_discussions']} discussions, "
                     f"{m['n_benign_agents']} benign agents)")
        lines.append(f"  private contamination : {_bar(m['private_contamination_rate'])}")
        lines.append(f"  public endorsement    : {_bar(m['public_endorsement_rate'])}")
        lines.append(f"  private/public diverge: {_bar(m['divergence_rate'])}")
    lines.append("")
    lines.append("private contamination = share of benign agents whose FINAL private")
    lines.append("probe answer matches the adversary's false answer.")
    lines.append("divergence = privately believes false while NOT endorsing it publicly.")
    return "\n".join(lines)


def render_html(agg: dict, title: str = "beliefcollapse report") -> str:
    rows = []
    for cond, m in agg["by_condition"].items():
        def cell(r):
            pct = f"{r:.1%}" if r is not None else "n/a"
            w = int((r or 0) * 100)
            color = "#c0392b" if (r or 0) >= 0.3 else ("#e67e22" if (r or 0) >= 0.1 else "#27ae60")
            return (f'<td><div style="background:#eee;width:120px;display:inline-block">'
                    f'<div style="background:{color};width:{w}px">&nbsp;</div></div> {pct}</td>')
        rows.append(
            f"<tr><td><b>{html.escape(cond)}</b><br><small>{m['n_discussions']} discussions, "
            f"{m['n_benign_agents']} agents</small></td>"
            f"{cell(m['private_contamination_rate'])}"
            f"{cell(m['public_endorsement_rate'])}"
            f"{cell(m['divergence_rate'])}</tr>")
    return f"""<!doctype html><html><head><meta charset="utf-8">
<title>{html.escape(title)}</title>
<style>body{{font-family:system-ui,sans-serif;max-width:760px;margin:2em auto;padding:0 1em}}
table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #ddd;padding:8px;text-align:left}}
th{{background:#f6f6f6}}</style></head><body>
<h1>{html.escape(title)}</h1>
<p>Open audit harness for <b>private-belief contamination</b> in multi-agent LLM
discussions (protocol: arXiv 2610.22138). Private contamination = share of benign
agents whose <i>final private probe</i> matches the adversary's false answer.</p>
<table><tr><th>condition</th><th>private contamination</th><th>public endorsement</th>
<th>private/public divergence</th></tr>
{''.join(rows)}</table>
<p><small>Generated by <a href="https://github.com/habib-analyst/beliefcollapse">beliefcollapse</a>
(open source, $0).</small></p></body></html>"""
